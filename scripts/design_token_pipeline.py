"""
Design Token Pipeline — Extracts tokens from figma-tokens.json and generates:
1. CSS custom properties (globals.css variables)
2. Tailwind config color map
3. TypeScript design token constants
4. Figma-ready Tokens Studio JSON (with light + dark modes)

Usage:
    python scripts/design_token_pipeline.py                 # Generate all outputs
    python scripts/design_token_pipeline.py --format css     # CSS only
    python scripts/design_token_pipeline.py --format tailwind
    python scripts/design_token_pipeline.py --format typescript
    python scripts/design_token_pipeline.py --format figma   # Tokens Studio JSON
    python scripts/design_token_pipeline.py --verify         # Verify code ↔ tokens sync

Source of truth: docs/figma-tokens.json
"""

import json
import re
import argparse
from pathlib import Path
from datetime import datetime, timezone

# ── Paths ──────────────────────────────────────────────────────────────
PROJECT_ROOT = Path(__file__).parent.parent
TOKENS_FILE = PROJECT_ROOT / "docs" / "figma-tokens.json"
OUTPUT_DIR = PROJECT_ROOT / "docs" / "generated"
GLOBALS_CSS = PROJECT_ROOT / "frontend" / "src" / "app" / "globals.css"
TAILWIND_CONFIG = PROJECT_ROOT / "frontend" / "tailwind.config.ts"
DESIGN_SYSTEM_TS = PROJECT_ROOT / "frontend" / "src" / "lib" / "design-tokens.ts"

# ── Light mode overrides (tokens file stores dark mode as default) ─────
LIGHT_MODE_OVERRIDES = {
    "colors.bg.primary": "#F8FAFB",
    "colors.bg.secondary": "#EFF3F6",
    "colors.accent": "#00A89F",
    "colors.text.primary": "#1A2332",
    "colors.text.secondary": "#5A6B7D",
    "colors.border": "#D1D5DB",
    "colors.surface.0": "#F8FAFB",
    "colors.surface.1": "#FFFFFF",
    "colors.surface.2": "#F1F5F9",
    "colors.surface.3": "#E2E8F0",
    "colors.surface.4": "#CBD5E1",
}


def load_tokens() -> dict:
    """Load the canonical token file."""
    with open(TOKENS_FILE) as f:
        return json.load(f)


def flatten_tokens(obj: dict, prefix: str = "") -> dict[str, dict]:
    """Flatten nested token structure into dot-path → {value, type, description}."""
    result = {}
    for key, val in obj.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(val, dict) and "value" in val:
            result[path] = val
        elif isinstance(val, dict):
            result.update(flatten_tokens(val, path))
    return result


# ── CSS Generation ─────────────────────────────────────────────────────

def generate_css(tokens: dict) -> str:
    """Generate CSS custom properties for light and dark modes."""
    flat = flatten_tokens(tokens.get("global", {}))
    colors = {k: v for k, v in flat.items() if v.get("type") == "color"}

    lines = [
        "/* ═══ AUTO-GENERATED by design_token_pipeline.py ═══ */",
        f"/* Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} */",
        f"/* Source: docs/figma-tokens.json ({len(colors)} color tokens) */",
        "",
        "/* ── Light Mode ─────────────────────────────────── */",
        ":root {",
    ]

    for path, token in sorted(colors.items()):
        css_var = "--oc-" + path.replace("colors.", "").replace(".", "-")
        light_val = LIGHT_MODE_OVERRIDES.get(path, token["value"])
        desc = token.get("description", "")
        comment = f"  /* {desc} */" if desc else ""
        lines.append(f"  {css_var}: {light_val};{comment}")

    lines.append("}")
    lines.append("")
    lines.append("/* ── Dark Mode ──────────────────────────────────── */")
    lines.append(".dark {")

    for path, token in sorted(colors.items()):
        css_var = "--oc-" + path.replace("colors.", "").replace(".", "-")
        lines.append(f"  {css_var}: {token['value']};")

    lines.append("}")
    lines.append("")

    # Spacing tokens
    spacing = {k: v for k, v in flat.items() if v.get("type") == "spacing"}
    if spacing:
        lines.append("/* ── Spacing Scale ──────────────────────────────── */")
        lines.append(":root {")
        for path, token in sorted(spacing.items(), key=lambda x: int(x[0].split(".")[-1])):
            css_var = "--oc-space-" + path.split(".")[-1]
            lines.append(f"  {css_var}: {token['value']}px;")
        lines.append("}")
        lines.append("")

    # Border radius tokens
    radii = {k: v for k, v in flat.items() if v.get("type") == "borderRadius"}
    if radii:
        lines.append("/* ── Border Radius ─────────────────────────────── */")
        lines.append(":root {")
        for path, token in sorted(radii.items()):
            name = path.split(".")[-1]
            css_var = f"--oc-radius-{name}"
            lines.append(f"  {css_var}: {token['value']}px;")
        lines.append("}")
        lines.append("")

    return "\n".join(lines)


# ── Tailwind Generation ────────────────────────────────────────────────

def generate_tailwind_colors(tokens: dict) -> str:
    """Generate Tailwind-compatible color config object."""
    flat = flatten_tokens(tokens.get("global", {}).get("colors", {}))

    def build_nested(flat_items: dict) -> dict:
        tree: dict = {}
        for path, token in flat_items.items():
            parts = path.split(".")
            current = tree
            for i, part in enumerate(parts[:-1]):
                if part not in current:
                    current[part] = {}
                current = current[part]
            current[parts[-1]] = token["value"]
        return tree

    nested = build_nested(flat)
    return json.dumps(nested, indent=2)


# ── TypeScript Generation ──────────────────────────────────────────────

def generate_typescript(tokens: dict) -> str:
    """Generate TypeScript design token constants and types."""
    flat = flatten_tokens(tokens.get("global", {}))
    colors = {k: v for k, v in flat.items() if v.get("type") == "color"}
    spacing = {k: v for k, v in flat.items() if v.get("type") == "spacing"}
    radii = {k: v for k, v in flat.items() if v.get("type") == "borderRadius"}
    fonts = {k: v for k, v in flat.items() if "fontFamilies" in v.get("type", "")}
    sizes = {k: v for k, v in flat.items() if "fontSizes" in v.get("type", "")}
    weights = {k: v for k, v in flat.items() if "fontWeights" in v.get("type", "")}

    def ts_key(name: str) -> str:
        """Quote keys that aren't valid JS identifiers (start with digit, contain -)."""
        if name[0].isdigit() or "-" in name:
            return f'"{name}"'
        return name

    lines = [
        "/**",
        " * OpenClaw Design System Tokens",
        f" * Auto-generated by design_token_pipeline.py on {datetime.now(timezone.utc).strftime('%Y-%m-%d')}",
        f" * Source: docs/figma-tokens.json ({len(flat)} tokens total)",
        " *",
        " * DO NOT EDIT MANUALLY — edit figma-tokens.json and re-run the pipeline.",
        " */",
        "",
        "// ── Color Tokens (dark mode values) ──────────────────────────────",
        "",
        "export const colors = {",
    ]

    # Group colors by top-level category
    categories: dict[str, list] = {}
    for path, token in sorted(colors.items()):
        clean = path.replace("colors.", "")
        parts = clean.split(".")
        cat = parts[0] if len(parts) > 1 else "_root"
        if cat not in categories:
            categories[cat] = []
        categories[cat].append((clean, token))

    for cat, items in categories.items():
        if cat == "_root":
            for clean, token in items:
                desc = token.get("description", "")
                comment = f" // {desc}" if desc else ""
                key = ts_key(clean)
                lines.append(f'  {key}: "{token["value"]}",{comment}')
        else:
            lines.append(f"  {cat}: {{")
            for clean, token in items:
                leaf = clean.split(".")[-1]
                desc = token.get("description", "")
                comment = f" // {desc}" if desc else ""
                key = ts_key(leaf)
                lines.append(f'    {key}: "{token["value"]}",{comment}')
            lines.append("  },")

    lines.append("} as const;")
    lines.append("")

    # Light mode overrides
    lines.append("export const lightModeOverrides = {")
    for path, val in sorted(LIGHT_MODE_OVERRIDES.items()):
        key = ts_key(path.replace("colors.", "").replace(".", "_"))
        lines.append(f'  {key}: "{val}",')
    lines.append("} as const;")
    lines.append("")

    # Spacing
    lines.append("export const spacing = {")
    for path, token in sorted(spacing.items(), key=lambda x: int(x[0].split(".")[-1])):
        name = path.split(".")[-1]
        lines.append(f"  {ts_key(name)}: {token['value']},")
    lines.append("} as const;")
    lines.append("")

    # Border radius
    lines.append("export const borderRadius = {")
    for path, token in sorted(radii.items()):
        name = path.split(".")[-1]
        lines.append(f'  {ts_key(name)}: "{token["value"]}px",')
    lines.append("} as const;")
    lines.append("")

    # Typography
    lines.append("export const typography = {")
    lines.append("  fontFamily: {")
    for path, token in sorted(fonts.items()):
        name = path.split(".")[-1]
        lines.append(f'    {ts_key(name)}: "{token["value"]}",')
    lines.append("  },")
    lines.append("  fontSize: {")
    for path, token in sorted(sizes.items()):
        name = path.split(".")[-1]
        px = token["value"]
        rem = round(int(px) / 16, 4)
        lines.append(f'    {ts_key(name)}: {{ px: {px}, rem: "{rem}rem" }},')
    lines.append("  },")
    lines.append("  fontWeight: {")
    for path, token in sorted(weights.items()):
        name = path.split(".")[-1]
        lines.append(f"    {ts_key(name)}: {token['value']},")
    lines.append("  },")
    lines.append("} as const;")
    lines.append("")

    # Chart palette as array (useful for recharts)
    chart_colors = sorted(
        [(k, v) for k, v in colors.items() if "chart" in k],
        key=lambda x: x[0]
    )
    lines.append("/** Chart palette — use with recharts or any charting library */")
    lines.append("export const chartPalette = [")
    for path, token in chart_colors:
        desc = token.get("description", "")
        lines.append(f'  "{token["value"]}", // {desc}')
    lines.append("] as const;")
    lines.append("")

    # Data colors map (aquaculture-semantic)
    lines.append("/** Semantic data colors for aquaculture metrics */")
    lines.append("export const dataColors = {")
    data_colors = {k: v for k, v in colors.items() if k.startswith("colors.data.")}
    for path, token in sorted(data_colors.items()):
        name = path.split(".")[-1]
        lines.append(f'  {ts_key(name)}: "{token["value"]}", // {token.get("description", "")}')
    lines.append("} as const;")
    lines.append("")

    # Traffic light colors
    lines.append("/** Norwegian traffic light system (Trafikklyssystemet) */")
    lines.append("export const trafficLight = {")
    tl_colors = {k: v for k, v in colors.items() if k.startswith("colors.traffic.")}
    for path, token in sorted(tl_colors.items()):
        name = path.split(".")[-1]
        lines.append(f'  {ts_key(name)}: "{token["value"]}", // {token.get("description", "")}')
    lines.append("} as const;")
    lines.append("")

    # Type exports
    lines.append("// ── Type Exports ─────────────────────────────────────────────")
    lines.append("export type ColorToken = keyof typeof colors;")
    lines.append("export type DataMetric = keyof typeof dataColors;")
    lines.append("export type TrafficColor = keyof typeof trafficLight;")
    lines.append("export type SpacingScale = keyof typeof spacing;")
    lines.append("export type FontSize = keyof typeof typography.fontSize;")
    lines.append("")

    return "\n".join(lines)


# ── Figma Tokens Studio JSON (with light + dark modes) ─────────────────

def generate_figma_tokens(tokens: dict) -> str:
    """Generate Tokens Studio compatible JSON with light+dark modes."""
    global_tokens = tokens.get("global", {})
    flat_colors = flatten_tokens(global_tokens.get("colors", {}))

    # Build light mode set
    light: dict = {}
    dark: dict = {}

    for path, token in flat_colors.items():
        parts = path.split(".")
        dark_val = token["value"]
        light_val = LIGHT_MODE_OVERRIDES.get(f"colors.{path}", dark_val)

        # Build nested structure
        for mode_dict, val in [(light, light_val), (dark, dark_val)]:
            current = mode_dict
            for p in parts[:-1]:
                if p not in current:
                    current[p] = {}
                current = current[p]
            current[parts[-1]] = {
                "value": val,
                "type": "color",
                "description": token.get("description", ""),
            }

    result = {
        "light": {"colors": light},
        "dark": {"colors": dark},
        "global": {
            "typography": global_tokens.get("typography", {}),
            "spacing": global_tokens.get("spacing", {}),
            "borderRadius": global_tokens.get("borderRadius", {}),
        },
        "$themes": [
            {"id": "light", "name": "Light", "selectedTokenSets": {"light": "enabled", "global": "enabled"}},
            {"id": "dark", "name": "Dark", "selectedTokenSets": {"dark": "enabled", "global": "enabled"}},
        ],
    }

    return json.dumps(result, indent=2)


# ── Verification ───────────────────────────────────────────────────────

def verify_sync() -> list[str]:
    """Verify that code tokens match figma-tokens.json. Returns list of issues."""
    tokens = load_tokens()
    flat = flatten_tokens(tokens.get("global", {}))
    colors = {k: v for k, v in flat.items() if v.get("type") == "color"}
    issues = []

    # Check globals.css
    if GLOBALS_CSS.exists():
        css_content = GLOBALS_CSS.read_text()
        dark_section = css_content.split(".dark {")[-1].split("}")[0] if ".dark {" in css_content else ""

        for path, token in colors.items():
            # Only check a few key tokens to avoid false positives
            hex_val = token["value"].upper()
            if path.startswith("colors.chart.") or path.startswith("colors.data.") or path.startswith("colors.traffic."):
                if hex_val.lower() not in css_content.lower():
                    issues.append(f"CSS missing: {path} = {token['value']}")

    # Check tailwind.config.ts
    if TAILWIND_CONFIG.exists():
        tw_content = TAILWIND_CONFIG.read_text()
        for path, token in colors.items():
            if path.startswith("colors.chart."):
                num = path.split(".")[-1]
                expected = f"'{token['value']}'"
                if expected not in tw_content and f'"{token["value"]}"' not in tw_content:
                    issues.append(f"Tailwind missing chart.{num}: {token['value']}")

    return issues


# ── Main ───────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="OpenClaw Design Token Pipeline")
    parser.add_argument("--format", choices=["css", "tailwind", "typescript", "figma", "all"], default="all")
    parser.add_argument("--verify", action="store_true", help="Verify code ↔ token sync")
    parser.add_argument("--output-dir", type=str, default=None, help="Custom output directory")
    args = parser.parse_args()

    tokens = load_tokens()
    flat = flatten_tokens(tokens.get("global", {}))
    print(f"Loaded {len(flat)} tokens from {TOKENS_FILE}")

    out = Path(args.output_dir) if args.output_dir else OUTPUT_DIR
    out.mkdir(parents=True, exist_ok=True)

    if args.verify:
        issues = verify_sync()
        if issues:
            print(f"\n{len(issues)} sync issues found:")
            for issue in issues:
                print(f"  - {issue}")
        else:
            print("All tokens in sync!")
        return

    if args.format in ("css", "all"):
        css = generate_css(tokens)
        (out / "design-tokens.css").write_text(css, encoding="utf-8")
        print(f"  CSS: {out / 'design-tokens.css'} ({len(css.splitlines())} lines)")

    if args.format in ("tailwind", "all"):
        tw = generate_tailwind_colors(tokens)
        (out / "tailwind-colors.json").write_text(tw, encoding="utf-8")
        print(f"  Tailwind: {out / 'tailwind-colors.json'}")

    if args.format in ("typescript", "all"):
        ts = generate_typescript(tokens)
        # Also write directly to frontend/src/lib/
        DESIGN_SYSTEM_TS.parent.mkdir(parents=True, exist_ok=True)
        DESIGN_SYSTEM_TS.write_text(ts, encoding="utf-8")
        (out / "design-tokens.ts").write_text(ts, encoding="utf-8")
        print(f"  TypeScript: {DESIGN_SYSTEM_TS}")
        print(f"  TypeScript: {out / 'design-tokens.ts'} (copy)")

    if args.format in ("figma", "all"):
        figma = generate_figma_tokens(tokens)
        (out / "figma-tokens-studio.json").write_text(figma, encoding="utf-8")
        # Also update the main tokens file with light+dark modes
        (PROJECT_ROOT / "docs" / "figma-tokens-studio.json").write_text(figma, encoding="utf-8")
        print(f"  Figma: {out / 'figma-tokens-studio.json'}")
        print(f"  Figma: docs/figma-tokens-studio.json (Tokens Studio import)")

    print(f"\nDone! {len(flat)} tokens processed.")


if __name__ == "__main__":
    main()
